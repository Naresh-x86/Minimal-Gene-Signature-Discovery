"""
benchmark.py — HPC scaling benchmark for the candidate-scoring kernel.

What is benchmarked?
--------------------
The INNERMOST computation of each greedy step:

    "Given N candidate genes, score ALL of them simultaneously."

This is the bottleneck that benefits most from parallelism, because:
  - Scoring candidates is embarrassingly parallel.
  - The work scales linearly with N_candidates.

Why synthetic data?
-------------------
The real dataset has ~500 candidates.  To see where the GPU advantage
truly kicks in, we scale N_candidates from 100 → 10,000 using randomly
generated data with the SAME dimensions as GSE2034:
  n_samples = 286  (same as real)
  n_pos     = 106  (same class balance as real)
  n_neg     = 180

What varies?
------------
  ┌─────────────────────┬───────────────────────────────────────┐
  │ Implementation      │ How candidates are scored             │
  ├─────────────────────┼───────────────────────────────────────┤
  │ Sequential (1 core) │ Python loop, one gene at a time       │
  │ Parallel CPU        │ joblib threads, N_candidates / n_jobs │
  │ GPU (RTX 4060)      │ Single batched tensor operation        │
  └─────────────────────┴───────────────────────────────────────┘

Expected output
---------------
  results/benchmark_results.csv
  results/figures/05_hpc_speedup.png  (generated by make_figures.py)
"""

import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).parent.parent))
from src.config import (
    BENCHMARK_CPU_WORKERS,
    BENCHMARK_N_SAMPLES,
    BENCHMARK_N_POS,
    BENCHMARK_N_NEG,
    BENCHMARK_PROBLEM_SIZES,
    BENCHMARK_REPEATS,
    RESULTS_DIR,
)
from src.utils import auc_from_scores

try:
    from joblib import Parallel, delayed
    JOBLIB_OK = True
except ImportError:
    JOBLIB_OK = False

try:
    import torch
    TORCH_OK = True
except ImportError:
    TORCH_OK = False


# ─── Scoring kernels ───────────────────────────────────────────────────────────

def _sequential(proj: np.ndarray, cands: np.ndarray, y: np.ndarray) -> np.ndarray:
    """Score each candidate in a Python for-loop (baseline)."""
    aucs = np.empty(len(cands))
    for i, cand in enumerate(cands):
        combined   = proj + cand
        pos        = combined[y == 1]
        neg        = combined[y == 0]
        wins       = (pos[:, None] > neg[None, :]).sum()
        auc        = wins / (len(pos) * len(neg))
        aucs[i]    = max(auc, 1 - auc)
    return aucs


def _parallel_cpu(
    proj: np.ndarray, cands: np.ndarray, y: np.ndarray, n_jobs: int
) -> np.ndarray:
    """Score candidates in parallel across CPU threads."""
    def _one(i):
        combined = proj + cands[i]
        return auc_from_scores(combined, y)

    return np.array(
        Parallel(n_jobs=n_jobs, prefer="threads")(delayed(_one)(i) for i in range(len(cands)))
    )


def _gpu(proj: np.ndarray, cands: np.ndarray, y: np.ndarray) -> np.ndarray:
    """Score all candidates in one GPU batched operation."""
    from src.gpu_search import score_all_candidates_gpu
    dev    = torch.device("cuda")
    proj_t = torch.tensor(proj,        dtype=torch.float32, device=dev)
    cand_t = torch.tensor(cands,       dtype=torch.float32, device=dev)
    y_t    = torch.tensor(y == 1,      dtype=torch.bool,    device=dev)
    torch.cuda.synchronize()
    result = score_all_candidates_gpu(proj_t, cand_t, y_t)
    torch.cuda.synchronize()
    return result.cpu().numpy()


# ─── Timing helper ─────────────────────────────────────────────────────────────

def _time(fn, repeats: int = BENCHMARK_REPEATS):
    """Return (mean_s, std_s) averaged over `repeats` independent runs."""
    times = []
    for _ in range(repeats):
        t0 = time.perf_counter()
        fn()
        times.append(time.perf_counter() - t0)
    return float(np.mean(times)), float(np.std(times))


# ─── Main benchmark ────────────────────────────────────────────────────────────

def run_benchmark(save_dir: Path = RESULTS_DIR) -> pd.DataFrame:
    """
    Run the full HPC benchmark across problem sizes and implementations.

    Returns
    -------
    pd.DataFrame with columns:
        n_candidates, implementation, n_workers, mean_s, std_s, speedup
    """
    save_dir = Path(save_dir)
    save_dir.mkdir(parents=True, exist_ok=True)

    rng  = np.random.default_rng(42)
    y    = np.concatenate([np.ones(BENCHMARK_N_POS, int), np.zeros(BENCHMARK_N_NEG, int)])
    proj = rng.standard_normal(BENCHMARK_N_SAMPLES).astype(np.float32)

    records = []

    for n_cands in BENCHMARK_PROBLEM_SIZES:
        cands = rng.standard_normal((n_cands, BENCHMARK_N_SAMPLES)).astype(np.float32)
        print(f"\n── N_candidates = {n_cands:,} ──────────────────────────")

        # ── 1. Sequential baseline ────────────────────────────────────────
        m, s = _time(lambda: _sequential(proj, cands, y))
        seq_time = m
        print(f"  sequential (1-core)  : {m:.4f}s ± {s:.4f}s")
        records.append(dict(
            n_candidates=n_cands, implementation="sequential",
            n_workers=1, mean_s=m, std_s=s,
        ))

        # ── 2. Parallel CPU ───────────────────────────────────────────────
        if JOBLIB_OK:
            for nw in BENCHMARK_CPU_WORKERS:
                m, s = _time(lambda nj=nw: _parallel_cpu(proj, cands, y, nj))
                spd  = seq_time / m
                print(f"  parallel {nw:2d}-core      : {m:.4f}s ± {s:.4f}s  (×{spd:.2f})")
                records.append(dict(
                    n_candidates=n_cands, implementation="parallel_cpu",
                    n_workers=nw, mean_s=m, std_s=s,
                ))

        # ── 3. GPU ────────────────────────────────────────────────────────
        if TORCH_OK and torch.cuda.is_available():
            # Warm-up run (first CUDA call pays JIT compilation cost)
            _gpu(proj, cands[:10], y)
            m, s = _time(lambda: _gpu(proj, cands, y))
            spd  = seq_time / m
            gpu_name = torch.cuda.get_device_name(0)
            print(f"  GPU ({gpu_name})  : {m:.4f}s ± {s:.4f}s  (×{spd:.2f})")
            records.append(dict(
                n_candidates=n_cands, implementation="gpu",
                n_workers=1, mean_s=m, std_s=s,
            ))
        elif TORCH_OK:
            print("  GPU : CUDA not available — skipping.")

    df = pd.DataFrame(records)

    # Compute speedup relative to sequential at same n_candidates
    seq_map = df[df.implementation == "sequential"].set_index("n_candidates")["mean_s"]
    df["speedup"] = df.apply(lambda r: seq_map[r.n_candidates] / r.mean_s, axis=1)

    out = save_dir / "benchmark_results.csv"
    df.to_csv(out, index=False)
    print(f"\n✓ Benchmark results → {out}")
    return df


# ─── CLI ──────────────────────────────────────────────────────────────────────

if __name__ == "__main__":
    df = run_benchmark()
    cols = ["n_candidates", "implementation", "n_workers", "mean_s", "speedup"]
    print(f"\nSummary:\n{df[cols].to_string(index=False)}")
